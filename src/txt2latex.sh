	} else { print; next }
}
section == "NAME" {
	#M $1 = "\\fB" $1
	$1 = "\\textbf{" $1 "}"
	#M sub(/ \- /, " \\fP- ")
}
section == "SYNOPSIS" {
	# Identify arguments of fcts and cmds
	if (type["SYNOPSIS"] == "") {
		if ($0 ~ /\(/)
			type["SYNOPSIS"] = "fct"
		else if ($1 == "struct" || $2 == "struct")
			type["SYNOPSIS"] = "struct"
		else if ($1 && $1 !~ /^#|typedef|struct|union|enum/)
			type["SYNOPSIS"] = "cmd"
	}
	if (type["SYNOPSIS"] == "cmd") {
		# Line is a command line
		if ($1 !~ /^\[/) {
			b = $1
			sub(/^\*/, "", b)
			#M subwords["\\<" b "\\>"] = "\\fB" b "\\fP"
			subwords["\\<" b "\\>"] = "\\textbf{" b "}"
		}
		for (i = 2; i <= NF; i++) {
			a = $i
			gsub(/[\[\]\|]/, "", a)
			if (a ~ /^[^\-]/)
				#M subwords["\\<" a "\\>"] = "\\fI" a "\\fP"
				subwords["\\<" a "\\>"] = "\\textit{" a "}"
		}
	} else if (type["SYNOPSIS"] == "fct") {
		# Line is a C function definition
		if ($1 == "typedef") {
			if ($0 !~ /\(\*/)
				#M subwords["\\<" $2 "\\>"] = "\\fI" $2 "\\fP"
				subwords["\\<" $2 "\\>"] = "\\textit{" $2 "}"
		} else if ($1 == "#define")
			#M subwords["\\<" $2 "\\>"] = "\\fI" $2 "\\fP"
			subwords["\\<" $2 "\\>"] = "\\textit{" $2 "\\}"
		for (i = 1; i <= NF; i++) {
			if ($i ~ /[,\)];*$/) {
				a = $i
				sub(/.*\(/, "", a)
				gsub(/\W/, "", a)
				#M subwords["\\<" a "\\>"] = "\\fI" a "\\fP"
				subwords["\\<" a "\\>"] = "\\textit{" a "}"
			}
		}
	}
}
{
