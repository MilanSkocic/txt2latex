expand $@ | 
gawk --re-interval -v head="$head" -v title="$title" -v author="$author" -v date="$date" \
 -v itxt="$itxt" \
 -v btxt="$btxt" \
 -v ptxt="$ptxt" '
BEGIN {
	print head
	avar[1] = btxt; avar[2] = itxt
	for (k in avar) {
		#M mark = (k == 1) ? "\\fB" : "\\fI"
		mark = (k == 1) ? "\\textbf{" : "\\textit{"
		split(avar[k], tt, "§")
		for (i in tt)
			if (tt[i] != "")
				#M subwords["\\<" tt[i] "\\>"] = mark tt[i] "\\fP"
				subwords["\\<" tt[i] "\\>"] = mark tt[i] "}"
		for (i in tt)
			delete tt[i]
	}
	for (k in avar)
		delete avar[k]

    if (title != "") {
        start_article(title, author, date); 
        start_document()
    }
}
END{ 
    #M 
    in_list=end_list(in_list,"itemize")
    in_desc=end_list(in_desc,"description")
    in_enum=end_list(in_enum,"enumerate")
    in_bd=end_list(in_bd, "verbatim")
