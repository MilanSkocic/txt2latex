	for (i = 1; i <= NF; i++) {
		b = $i
		sub(/^\*/, "", b)
		if ((a = index(b, ")(")) > 3) {
			w = substr(b, 3, a - 3)
			#M subwords["\\<" w "\\>"] = "\\fI" w "\\fP"
			subwords["\\<" w "\\>"] = "\\textit{" w "}"
		}
		if ((a = index(b, "(")) > 1) {
			w = substr(b, 1, a - 1)
			#M subwords["\\<" w "\\("] = "\\fB" w "\\fP("
			subwords["\\<" w "\\("] = "\\textbf{" w "}("
		}
	}
	# word attributes
	n = asorti(subwords, indices)
	for (i = 1; i <= n; i++)
		gsub(indices[i], subwords[indices[i]])
	# shell options
	#M gsub(/\b\-+\w+(\-\w+)*/, "\\fb&\\fp")
	gsub(/\b\-+\w+(\-\w+)*/, "\\textbf{&}")
	# unprotect dots inside words
	gsub(/_dOt_/, ".")

    if (section == "SYNOPSIS") {
		sub(/^  /, "")
		print
		next
	}
	if (match($0, /[^ ]  +/) > 0) {
		# tag list item
        #M
        if ((in_desc+0) == 0){
            in_desc = start_list(in_desc, "description")
        }
		adjust_indent()
		tag = substr($0, 1, RSTART)
		sub(/^ */, "", tag)
		if (RSTART+RLENGTH < length())
			$0 = substr($0, RSTART + RLENGTH)
		else
			$0 = ""
        #M print ".TP\n.B"
        print "\\item[" tag "]"
		#M print tag
		prevblankline = 0
		if (NF == 0)
			next
	} else if ($1 == "-"||$1 == "o"||$1 == "*") {
		# bullet list item
        #M
        if ((in_list+0) == 0){
            in_list = start_list(in_item, "itemize")
        }
		adjust_indent()
		#M print ".IP \\(bu 3"
        print "\\item"
		prevblankline = 0
		$1 = ""
	} else if ($1 ~ /^[0-9]+[\).]$/) {
		# enum list item
        if ((in_enum+0) == 0){
            in_enum = start_list(in_item, "enumerate")
        }
		adjust_indent()
		#M print ".IP " $1 " 4"
        print "\\item"
		prevblankline = 0
		$1 = ""
	} else if (pls == 0) {
		# new paragraph
		adjust_indent()
	} else if (NF == 0) {
		# blank line
        # print "BLANK"
		prevblankline = 1
        in_list=end_list(in_list,"itemize")
        in_desc=end_list(in_desc,"description")
        in_enum=end_list(in_enum,"enumerate")
        print $0
		next
	} else
		prevblankline = 0
	# flush vertical space
	if (prevblankline == 1) {
		#M print ".PP"
		prevblankline = 0
	}
	if (section != "SYNOPSIS" || $0 ~ /^ {1,4}/)
		sub(/ */,"")
	# Protect lines starting by simple quotes
	sub(/^'\''/, "\\(cq")
	print
}



function adjust_indent(){
	if (ls > ind[ni]) {
		ind[++ni] = ls
		#M print ".RS"
	} else if (ls < ind[ni]) {
		while (ls < ind[ni]) {
			ni--
			#M print ".RE"
		}
	}
}

function escape (s){
    gsub(/\\/, "\\textbackslash\\", s)
    gsub(/#/,"\\#", s)
    gsub(/\$/,"\\$", s)
    gsub(/%/,"\\%", s)
    gsub(/&/,"\\\\&", s)
    gsub(/{/, "\\{", s)
    gsub(/}/, "\\}", s)
    gsub(/_/, "\\\_", s)
    gsub(/\^/, "\\^\\", s)
    return s
}

function fmtmath (s){
    line = s
    math=""
    text=""
    sout=""
    i=0
    in_math = 0
    while (match(line, /\$([^$]*)\$/, m)) {
        in_math=1
        math = m[0]
        text = substr(line, i, i+RSTART-1)
        line = substr(line, RSTART + RLENGTH)
        text = escape(text)
        sout = sout text math
    }
    if (in_math == 1) {
        line = escape(line)
        sout = sout line
    }else{
        sout = escape(line)
    }

    return sout
}

function end_list(s, env){
    if ((s+0)==1){
        print "\\end{"env"}"
    }
    return 0
}

function start_list(s, env){
    if ((s+0)==0){
        print "\\begin{"env"}"
    }
    return 1
}

function start_article(title,author,date) { 
