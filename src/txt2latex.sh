	#M Do nothing for equation environment $$...$$
    if (match($0,/[[:space:]].*\$\$(.*)\$\$/)>0) {
        print $0
        next
    }
    #M Format lines with inline math
    if ((in_bd+0) == 0) {
        $0=fmtmath($0)
    }

    # to avoid some side effects in regexp
	gsub(/\.\.\./, "\\ldots")
	# remove spaces in empty lines
	sub(/^ +$/,"")
}
/^[[:upper:][:digit:]]+[[:upper:][:space:][:digit:][:punct:]]+$/ {
	# Section header
	if ((in_bd + 0) == 1) {
		in_bd = 0
		#M print ".fam T\n.fi"
        print "\\end{verbatim}"
	}
	if (section == "SYNOPSIS") {
		#M print ".fam T\n.fi"
		type["SYNOPSIS"] = ""
	}
	if ($0 ~/^[^[:space:]]/)
		#M print ".SH " $0
		print "\\section{" $0 "}"
	else
		#M print ".SS" $0
		print "\\subsection{" $0 "}"
	sub(/^ +/, "")
	section = $0
	if (section == "SYNOPSIS") {
		#M print ".nf\n.fam C"
		#M in_bd = 1
	}
	ls = 0		# line start index
	pls = 0		# previous line start index
	pnzls = 0	# previous non zero line start index
	ni = 0		# indent level
	ind[0] = 0	# indent offset table
	prevblankline = 0
	next
}
{
	# Compute line start index, handle start of example display block
	pls = ls
	if (ls != 0)
		pnzls = ls
	match($0, /[^ ]/)
	ls = RSTART
	if (in_bd == 0 && pls == 0 && pnzls > 0 && ls > pnzls && $1 !~ /^[\-\*o]$|^[0-9]+\.$/) {
		# example display block
		if (prevblankline == 1) {
			#M print ".PP"
			prevblankline = 0
		}
		#M print ".nf\n.fam C"
        in_bd = start_list(in_bd, "verbatim")
		eoff = ls
	}
	if (ls > 0 && ind[0] == 0)
		ind[0] = ls
}
(in_bd + 0) == 1 {
	# In block display
	if (section == "SYNOPSIS")
		;
	else if (ls != 0 && ls < eoff) {
		# End of literal display block
		#in_bd = 0
		#M print ".fam T\n.fi"
